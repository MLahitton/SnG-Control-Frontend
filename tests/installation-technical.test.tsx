import { fireEvent, render, screen } from "@testing-library/react";
import userEvent from "@testing-library/user-event";
import { expect, it, vi } from "vitest";
import { TechnicalFields } from "@/features/measurements/TechnicalFields";
import { mmToMetres, metresToMm } from "@/features/measurements/units";
import type { Structure } from "@/features/measurements/contracts";
const structure: Structure = { id: "unit-1", itemId: null, unitOrdinal: 1, unitCount: 1, itemNumber: null, description: "Original", location: null, width: 1, height: 2, actualWidth: 2, actualHeight: 2.4, actualSystemText: "Libre", createdAt: "", measuredAt: null, retiredAt: null };
it("uses centralized explicit mm conversions", () => { expect(mmToMetres(2000)).toBe(2); expect(mmToMetres(2400)).toBe(2.4); expect(metresToMm(2)).toBe(2000); expect(metresToMm(2.4)).toBe(2400); expect(metresToMm(1.2345)).toBe(1234.5); });
it("keeps 1100 a suggestion until explicit confirmation; clears conditional values", async () => {
 const save = vi.fn(); render(<TechnicalFields structure={structure} writable disabled={false} onCommand={save} onDirty={vi.fn()} />);
 await userEvent.click(screen.getByText("Detalles técnicos"));
 expect(screen.queryByLabelText("Altura de manija (mm)")).not.toBeInTheDocument();
 await userEvent.selectOptions(screen.getByLabelText("Manija"), "Confirmed");
 expect(screen.getByLabelText(/Altura de manija/)).toHaveValue(null); expect(save).not.toHaveBeenCalled();
 await userEvent.click(screen.getByText("Confirmar 1100 mm")); expect(screen.getByLabelText(/Altura de manija/)).toHaveValue(1100);
 await userEvent.selectOptions(screen.getByLabelText("Referencia de vista"), "Outside");
 await userEvent.selectOptions(screen.getByLabelText("Tipo de apertura"), "HingedDoor");
 await userEvent.selectOptions(screen.getByLabelText("Dirección"), "Outward");
 await userEvent.selectOptions(screen.getByLabelText("Lado de bisagras desde la vista seleccionada"), "Left");
 await userEvent.selectOptions(screen.getByLabelText("Referencia de vista"), "Inside");
 expect(screen.getByLabelText("Lado de bisagras desde la vista seleccionada")).toHaveValue("Left");
 await userEvent.selectOptions(screen.getByLabelText("Alfajía"), "true");
 fireEvent.change(screen.getByLabelText("Medida de alfajía (mm)"), { target: { value: "120" } });
 await userEvent.click(screen.getByText("Guardar detalles técnicos"));
 expect(save).toHaveBeenLastCalledWith(expect.objectContaining({ technical: expect.objectContaining({ handleHeightMm: 1100, openingHand: "Left", viewSide: "Inside", alfajiaMeasurementMm: 120 }) }));
 await userEvent.selectOptions(screen.getByLabelText("Tipo de apertura"), "NotApplicable");
 await userEvent.selectOptions(screen.getByLabelText("Manija"), "NotApplicable");
 await userEvent.selectOptions(screen.getByLabelText("Alfajía"), "false");
 await userEvent.click(screen.getByText("Guardar detalles técnicos"));
 expect(save).toHaveBeenLastCalledWith(expect.objectContaining({ technical: expect.objectContaining({ handleHeightMm: null, openingDirection: null, openingHand: null, alfajiaMeasurementMm: null }) }));
});
it("rejects a handle taller than the actual structure and keeps read-only fields disabled", async () => {
 const { rerender } = render(<TechnicalFields structure={structure} writable disabled={false} onCommand={vi.fn()} onDirty={vi.fn()} />);
 await userEvent.click(screen.getByText("Detalles técnicos")); await userEvent.selectOptions(screen.getByLabelText("Manija"), "Confirmed");
 fireEvent.change(screen.getByLabelText(/Altura de manija/), { target: { value: "2401" } });
 expect(screen.getByRole("alert")).toBeInTheDocument(); expect(screen.getByText("Guardar detalles técnicos")).toBeDisabled();
 rerender(<TechnicalFields structure={structure} writable={false} disabled={false} onCommand={vi.fn()} onDirty={vi.fn()} />);
 expect(screen.getByLabelText("Manija")).toBeDisabled(); expect(screen.queryByText("Guardar detalles técnicos")).not.toBeInTheDocument();
});
